// Turns assets/figma/*.svg into src/svgs.ts so screens can render them with SvgXml.
// Run after adding or replacing an SVG: node scripts/build-svgs.js
const fs = require("fs");
const path = require("path");
const dir = path.join(__dirname, "..", "assets", "figma");
const out = path.join(__dirname, "..", "src", "svgs.ts");
const entries = fs.readdirSync(dir).filter((f) => f.endsWith(".svg")).sort().map((f) => {
  const key = f.replace(/\.svg$/, "").replace(/-([a-z])/g, (_, c) => c.toUpperCase());
  const xml = fs.readFileSync(path.join(dir, f), "utf8")
    .replace(/\s*preserveAspectRatio="none"/, "")
    .replace(/\s*style="display: block;"/, "")
    .replace(/\s*overflow="visible"/, "")
    .replace(/\s+/g, " ").trim();
  return `  ${key}: ${JSON.stringify(xml)},`;
});
fs.writeFileSync(out, `// Generated by scripts/build-svgs.js from assets/figma. Do not edit by hand.\nexport const svgs = {\n${entries.join("\n")}\n};\nexport type SvgName = keyof typeof svgs;\n`);
console.log(`wrote ${entries.length} svgs to src/svgs.ts`);
